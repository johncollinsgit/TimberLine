async function api(actor, command, query = '') {
  const response = await fetch(`${origin}/api?actor=${actor}${query}`, command ? { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ actor, command }) } : {});
  return { status: response.status, body: await response.json() };
}
