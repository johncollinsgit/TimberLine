import { chromium } from 'playwright';
import fs from 'node:fs';
const base=process.env.AI_TEST_URL || 'http://localhost:8798';
if(process.env.AI_TEST_FAKE_PROVIDER!=='1'||!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw new Error('Local fake-provider preview required');
const out=process.env.AI_TEST_OUTPUT_DIR;
if(!out)throw new Error('Set AI_TEST_OUTPUT_DIR for screenshots');
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
page.setDefaultTimeout(12000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const dispatches=()=>fs.existsSync(process.env.AI_TEST_DISPATCH_FILE)?fs.readFileSync(process.env.AI_TEST_DISPATCH_FILE,'utf8').split('\n').filter(Boolean).length:0;
const initialDispatches=dispatches();
try {
const firstPage=await page.goto(base+'/login');
if(firstPage.headers()['x-everbranch-ai-preview']!=='fictional-fake-provider')throw new Error('Guarded fake-provider router required');
await page.locator('input[name="email"]').fill('workspace-preview@example.test');
await page.locator('input[name="password"]').fill('Local-preview-only-482741');
await Promise.all([page.waitForURL(u=>!u.pathname.includes('/login')),page.locator('button[type="submit"]').click()]);
await page.goto(base+'/ai-branch?tenant=workspace-preview-field');
await page.getByRole('button',{name:'What needs attention?',exact:true}).waitFor();
if(dispatches()!==initialDispatches)throw new Error('Viewing context dispatched a provider request');
const requestId=await page.locator('form[action*="/briefings"] input[name="request_id"]').inputValue();
const token=await page.locator('form[action*="/briefings"] input[name="_token"]').inputValue();
await Promise.all([page.waitForURL(u=>u.searchParams.has('conversation')),page.getByRole('button',{name:'What needs attention?',exact:true}).click()]);
await page.getByRole('heading',{name:'Attention evidence, in priority order',exact:true}).waitFor();
const conversation=new URL(page.url()).searchParams.get('conversation');
const replay=await page.evaluate(async({token,requestId})=>{
 const r=await fetch('/ai-branch/briefings?tenant=workspace-preview-field',{method:'POST',headers:{'Content-Type':'application/json','Accept':'application/json','X-CSRF-TOKEN':token},body:JSON.stringify({request_id:requestId})});
 return {status:r.status,body:await r.json()};
},{token,requestId});
if(replay.status!==200||String(replay.body.conversation_id)!==conversation||dispatches()!==initialDispatches+1)throw new Error('Briefing replay duplicated or failed');
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:out+'/workspace-ai-desktop.png',fullPage:true});
const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:out+'/workspace-ai-mobile.png',fullPage:true});
const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const jobHref=await page.getByRole('link',{name:'Install entrance lighting',exact:true}).first().getAttribute('href');
await page.setViewportSize({width:1440,height:1100});
await page.goto(base+jobHref);
await page.getByRole('heading',{name:'Install entrance lighting',exact:true}).first().waitFor();
const aiLink=page.getByRole('link',{name:'AI Branch',exact:true}).first();
if(!(await aiLink.getAttribute('href')).includes('origin'))throw new Error('Missing launcher page context');
await aiLink.click();
await page.getByText('Context used',{exact:true}).first().click();
await page.getByText('Opened from: Install entrance lighting.',{exact:true}).waitFor();
if(dispatches()!==initialDispatches+1)throw new Error('Opening record context dispatched provider');
await page.goto(base+'/ai-branch?tenant=workspace-preview-followup');
if(await page.getByText('Keep field work summaries brief.',{exact:true}).count())throw new Error('Another workspace memory leaked');
await page.getByText('Use a warm tone in client drafts.',{exact:true}).waitFor();
await page.setViewportSize({width:390,height:844});
await Promise.all([page.waitForURL(u=>u.searchParams.has('conversation')),page.getByRole('button',{name:'What needs attention?',exact:true}).click()]);
await page.getByRole('heading',{name:'Attention evidence, in priority order',exact:true}).waitFor();
if(dispatches()!==initialDispatches+2)throw new Error('Unexpected provider dispatch count');
await page.setViewportSize({width:1440,height:1100});
await page.screenshot({path:out+'/workspace-ai-followup.png',fullPage:true});
if(await page.getByRole('link',{name:'Install entrance lighting',exact:true}).count())throw new Error('Another workspace source leaked');
console.log(JSON.stringify({desktopOverflow,mobileOverflow,privateReplay:true,recordLink:true,launcherContext:true,workspaceSwitch:true,provider:'fake only',dispatches:dispatches()-initialDispatches,pageErrors:errors},null,2));
if(desktopOverflow||mobileOverflow||errors.length)throw new Error('Layout or browser errors');
} finally { await browser.close(); }
