// Run only against the isolated local fixture described in the Trajectory runbook.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const url = process.env.TRAJECTORY_TEST_URL || 'http://127.0.0.1:8096';
assert.equal(new URL(url).hostname, '127.0.0.1', 'This mutating browser test is local-fixture only.');
(async () => {
  fs.mkdirSync('output/trajectory', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${url}/login`);
  await page.getByLabel('Email address').fill('owner@trajectory.test');
  await page.getByLabel('Password', { exact: true }).fill('Trajectory-local-preview-2026!');
  await Promise.all([page.waitForURL(u => !u.pathname.endsWith('/login')), page.getByRole('button', { name: 'Sign in', exact: true }).click()]);
  await page.goto(`${url}/trajectory`);
  await page.getByText('Where you’re headed', { exact: true }).waitFor();
  await page.screenshot({ path: 'output/trajectory/overview.png' });
  await page.locator('#tr-scenario').selectOption({ label: 'Spend 20% less' });
  await page.waitForResponse(r => r.url().includes('scenario_id=') && r.status() === 200);
  await page.locator('[data-chart="tr-forecast"]').click();
  await page.getByRole('dialog').getByRole('table').waitFor();
  await page.locator('#tr-close').click();
  await page.locator('[data-action="recommendation"]').first().click();
  const evidenceResponse = page.waitForResponse(r => r.url().endsWith('/evidence') && r.status() === 200);
  await page.getByRole('button', { name: 'View evidence', exact: true }).click();
  const evidence = await (await evidenceResponse).json();
  assert.ok(evidence.length > 0, 'Recommendations must open their supporting transactions.');
  await page.locator('.tr-table tbody tr').first().waitFor();
  await page.locator('[data-tab="bills"]').click();
  await page.getByRole('button', { name: 'Add goal', exact: true }).click();
  const goalName = `Browser test goal ${Date.now()}`;
  await page.getByLabel('Name', { exact: true }).fill(goalName);
  await page.getByLabel('Target amount', { exact: true }).fill('1000');
  await page.getByLabel('Already saved', { exact: true }).fill('100');
  await page.getByLabel('Monthly contribution', { exact: true }).fill('100');
  await page.getByLabel('Target date', { exact: true }).fill('2027-09-14');
  await page.locator('#tr-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByText(goalName, { exact: true }).waitFor();
  await page.locator('[data-tab="transactions"]').click();
  await page.locator('[data-action="classify"]').first().click();
  await page.getByLabel('Face Punched · unexpected, one time', { exact: true }).check();
  await page.locator('#tr-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.locator('.tr-table').getByText('Face Punched', { exact: true }).first().waitFor();
  await page.locator('[data-tab="assets"]').click();
  await page.getByRole('heading', { name: 'Gold and silver', exact: true }).waitFor();
  await page.screenshot({ path: 'output/trajectory/wealth.png' });
  await page.locator('[data-tab="connections"]').click();
  await page.getByRole('button', { name: 'Edit category defaults', exact: true }).click();
  await page.getByLabel('Entertainment', { exact: true }).uncheck();
  await page.locator('#tr-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Edit category defaults', exact: true }).click();
  assert.equal(await page.getByLabel('Entertainment', { exact: true }).isChecked(), false);
  await page.locator('#tr-close').click();
  await page.locator('[data-tab="medical"]').click();
  await page.getByRole('button', { name: 'Add medical need', exact: true }).click();
  const needName = `Sharing need ${Date.now()}`;
  await page.getByLabel('Name', { exact: true }).fill(needName);
  assert.equal(await page.getByLabel('Sharing ministry', { exact: true }).inputValue(), 'Samaritan Ministries');
  assert.equal(await page.getByLabel('Reserve received shares for this need’s unpaid bills', { exact: true }).isChecked(), true);
  await page.locator('#tr-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const needPanel = page.locator('section').filter({ has: page.getByRole('heading', { name: needName, exact: true }) });
  await needPanel.getByRole('button', { name: 'Add provider bill', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Fictional Prisma invoice');
  await page.getByLabel('Invoice reference (unique per provider)', { exact: true }).fill(`QA-${Date.now()}`);
  await page.getByLabel('Bill date', { exact: true }).fill(new Date().toISOString().slice(0,10));
  await page.getByLabel('Original bill', { exact: true }).fill('1500');
  await page.getByLabel('Already paid before tracked payments (do not repeat below)', { exact: true }).fill('500');
  await page.getByLabel('Monthly payment (or full balance for upfront payment)', { exact: true }).fill('250');
  const due = new Date(); due.setDate(due.getDate()+10);
  await page.getByLabel('Next unpaid payment date', { exact: true }).fill(due.toISOString().slice(0,10));
  await page.getByLabel('Interest-free plan reviewed; no separate debt record duplicates this bill', { exact: true }).check();
  await page.locator('#tr-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await needPanel.getByText('Fictional Prisma invoice · Prisma Health', { exact: true }).waitFor();
  await needPanel.getByRole('button', { name: 'Record expected / received share', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Fictional expected share');
  await page.getByLabel('Share amount', { exact: true }).fill('1000');
  await page.getByLabel('Expected or received date', { exact: true }).fill(due.toISOString().slice(0,10));
  await page.locator('#tr-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.locator('[data-chart="tr-medical"]').click();
  await page.getByRole('dialog').getByRole('table').waitFor();
  await page.locator('#tr-close').click();
  await page.screenshot({ path: 'output/trajectory/medical-sharing.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/trajectory/medical-sharing-mobile.png' });
  await page.locator('[data-tab="overview"]').click();
  await page.screenshot({ path: 'output/trajectory/mobile.png' });
  const bounds = await page.locator('#trajectory').boundingBox();
  assert.ok(bounds.x + bounds.width <= 391, 'Trajectory should fit a phone viewport.');
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: login, charts, scenario comparison, accessible chart tables, historical recommendation evidence, goal creation, transaction review, saved spending preferences, wealth view, medical needs/bills/shares, medical chart tables, and mobile layout.');
})().catch(error => { console.error(error); process.exit(1); });
