import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from 'playwright';

const origin = process.env.TEAM_SEARCH_ORIGIN || 'http://127.0.0.1:8775';
const evidence = resolve(process.env.SEARCH_EVIDENCE || '../search-evidence'); mkdirSync(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.DEMO_BROWSER_EXECUTABLE || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const errors = []; let checks = 0;
const check = (value, message) => { assert.ok(value, message); console.log('ok ' + ++checks + ' - ' + message); };
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1050 } });
  await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage(); page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
  const searchCalls = [];
  page.on('request', request => { if (request.url().includes('/team/search')) searchCalls.push(['request', request.url()]); });
  page.on('response', response => { if (response.url().includes('/team/search')) searchCalls.push(['response', response.status(), response.url()]); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto(origin + '/teams?tenant=fictional-evergreen');
  await page.locator('input[name=email]').fill('owner@fictional.invalid');
  await page.locator('input[name=password]').fill('Fictional-local-only-2026!');
  await page.locator('[data-test=login-button]').click();
  await page.goto(origin + '/teams?tenant=fictional-evergreen');
  await page.locator('#tw-count').filter({ hasText: 'tasks on page' }).waitFor();
  const input = page.locator('#eb-teams-query'), options = page.locator('#eb-teams-search .eb-search-option');
  await input.fill('north field entrance'); await options.first().waitFor();
  check((await options.allTextContents()).some(text => text.includes('Photograph the north field entrance')), 'real Teams endpoint returns stored task while typing');
  await input.press('ArrowDown'); await input.press('Enter'); await page.locator('#tw-title').waitFor({ state: 'visible' });
  await page.locator('#tw-title').fill('Unsaved search preservation note');
  await input.fill('> create task'); await options.filter({ hasText: 'Create task' }).waitFor({ timeout: 5000 }).catch(async error => { console.error(searchCalls); console.error(await page.evaluate(() => ({ available: globalThis.TeamSearchBridge?.available(), host: document.getElementById('eb-teams-search')?.hidden, status: document.getElementById('tw-status')?.textContent, search: document.querySelector('.eb-search-status')?.textContent, input: document.getElementById('eb-teams-query')?.value, rows: document.querySelector('.eb-search-list')?.innerText, panel: document.querySelector('.eb-search-panel')?.hidden, active: document.activeElement?.id }))); throw error; });
  await input.press('ArrowDown'); await input.press('Enter');
  check(await page.locator('#tw-title').inputValue() === 'Unsaved search preservation note', 'palette navigation preserves unsaved task title');
  check(!await page.locator('#tw-task-dialog').isVisible(), 'command respects the existing unsaved-work guard');
  await input.press('Escape');
  await page.screenshot({ path: resolve(evidence, 'teams-search-draft.png') });
  await page.reload(); await page.locator('#tw-count').filter({ hasText: 'tasks on page' }).waitFor();
  await page.keyboard.press('Control+k');
  check(await input.evaluate(node => node === document.activeElement), 'one Ctrl K handler launches global search');
  await input.fill('> create task'); await options.filter({ hasText: 'Create task' }).waitFor(); await input.press('ArrowDown'); await input.press('Enter');
  await page.locator('#tw-task-dialog[open]').waitFor();
  check(await page.locator('#tw-create-title').inputValue() === '', 'create task command opens canonical blank form');
  await page.keyboard.press('Escape'); await page.setViewportSize({ width: 390, height: 844 });
  await page.keyboard.press('Control+k'); await input.fill('north field entrance'); await options.first().waitFor();
  const mobilePanel = await page.locator('#eb-teams-search .eb-search-panel').boundingBox();
  check(Math.abs(mobilePanel.width - 390) < 1 && mobilePanel.x === 0, 'native Teams search fills the phone viewport');
  check(await page.locator('#eb-teams-search').getAttribute('aria-modal') === 'true', 'native phone search exposes dialog semantics');
  await page.screenshot({ path: resolve(evidence, 'teams-search-phone.png') });
  check(errors.length === 0, 'native Teams has no JavaScript errors');
  await context.close();
} finally { await browser.close(); }
